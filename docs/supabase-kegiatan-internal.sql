-- Skema kegiatan internal kantor.
--
-- Dipakai oleh dua project:
--   1. Portal admin utama (madujakbarsport-UPDATE) -> admin mengunggah foto
--      ke bucket "dokumentasi" dan mengisi tabel public.dokumentasi.
--   2. Website publik (kegiatan-internal-kantor) -> hanya membaca tabel yang
--      sama lewat role anon.
--
-- Jalankan skrip ini sekali di Supabase SQL Editor pada proyek yang dipakai
-- website utama. Skrip aman dijalankan berulang kali.

-- 1. Tabel kegiatan ---------------------------------------------------
create table if not exists public.dokumentasi (
  id bigint generated by default as identity primary key,
  judul text,
  keterangan text,
  tanggal date,
  storage_path text not null,
  storage_url text,
  urutan integer not null default 0,
  created_at timestamptz not null default now()
);

-- Kolom unit kerja (isi dari daftar unit kerja pada portal admin).
alter table public.dokumentasi add column if not exists unit_kerja text;

-- Kolom lama "cabang" tetap dipakai sebagai cadangan bila unit_kerja kosong.
alter table public.dokumentasi add column if not exists cabang text;

alter table public.dokumentasi enable row level security;

-- 2. Hak akses tabel ---------------------------------------------------
-- Role anon dan service_role pada proyek ini tidak selalu_mewarisi grant
-- default untuk tabel baru, sehingga SELECT/INSERT dapat ditolak dengan
-- error 42501 "permission denied for table dokumentasi". Grant di bawah
-- memastikan website publik bisa membaca dan portal admin bisa menulis.
grant usage on schema public to anon, authenticated, service_role;

grant select on public.dokumentasi to anon, authenticated, service_role;
grant insert, update, delete on public.dokumentasi to authenticated, service_role;

-- 3. Kebijakan RLS ----------------------------------------------------
drop policy if exists "Public can read dokumentasi" on public.dokumentasi;
create policy "Public can read dokumentasi"
  on public.dokumentasi for select to anon, authenticated
  using (true);

drop policy if exists "Admins can insert dokumentasi" on public.dokumentasi;
create policy "Admins can insert dokumentasi"
  on public.dokumentasi for insert to authenticated
  with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

drop policy if exists "Admins can update dokumentasi" on public.dokumentasi;
create policy "Admins can update dokumentasi"
  on public.dokumentasi for update to authenticated
  using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin')
  with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

drop policy if exists "Admins can delete dokumentasi" on public.dokumentasi;
create policy "Admins can delete dokumentasi"
  on public.dokumentasi for delete to authenticated
  using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

-- 4. Indeks bantu query daftar kegiatan -------------------------------
create index if not exists dokumentasi_tanggal_idx
  on public.dokumentasi (tanggal desc nulls last, created_at desc);

create index if not exists dokumentasi_unit_kerja_idx
  on public.dokumentasi (unit_kerja);

-- 5. Bucket penyimpanan foto ------------------------------------------
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('dokumentasi', 'dokumentasi', true, 8388608, array['image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do update
set name = excluded.name,
    public = excluded.public,
    file_size_limit = excluded.file_size_limit,
    allowed_mime_types = excluded.allowed_mime_types;

grant select on storage.objects to anon, authenticated;
grant insert, update, delete on storage.objects to authenticated, service_role;

drop policy if exists "Public can read dokumentasi photos" on storage.objects;
create policy "Public can read dokumentasi photos"
  on storage.objects for select to anon, authenticated
  using (bucket_id = 'dokumentasi');

drop policy if exists "Admins can upload dokumentasi photos" on storage.objects;
create policy "Admins can upload dokumentasi photos"
  on storage.objects for insert to authenticated
  with check (
    bucket_id = 'dokumentasi'
    and (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin'
  );

drop policy if exists "Admins can update dokumentasi photos" on storage.objects;
create policy "Admins can update dokumentasi photos"
  on storage.objects for update to authenticated
  using (
    bucket_id = 'dokumentasi'
    and (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin'
  )
  with check (
    bucket_id = 'dokumentasi'
    and (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin'
  );

drop policy if exists "Admins can delete dokumentasi photos" on storage.objects;
create policy "Admins can delete dokumentasi photos"
  on storage.objects for delete to authenticated
  using (
    bucket_id = 'dokumentasi'
    and (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin'
  );
