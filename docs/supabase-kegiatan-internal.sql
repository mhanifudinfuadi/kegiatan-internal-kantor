-- Skema "Kegiatan Internal Kantor" (website publik).
--
-- Sumber data tunggal: tabel public.kegiatan_internal_kantor + bucket storage
-- "dokumentasi". Tabel dan bucket ini diisi oleh portal admin utama
-- (madujakbarsport-UPDATE); website ini hanya membaca lewat role anon.
--
-- Jalankan skrip ini sekali di Supabase SQL Editor pada project yang dipakai
-- website (lihat NEXT_PUBLIC_SUPABASE_URL di .env.local). Skrip aman
-- dijalankan berulang kali (idempotent).
--
-- Isi skrip:
--   1. Tabel kegiatan_internal_kantor + kolom tambahan (multi-foto, unit kerja)
--   2. Tabel relasi kegiatan_internal_photos (opsional, dipakai bila ada)
--   3. Taksonomi unit kerja (jenis_kegiatan) + normalisasi data lama
--   4. View publik v_kegiatan_internal (dipakai website bila tersedia)
--   5. Function set_multi_foto() untuk menyimpan daftar foto satu kegiatan
--   6. Grant + kebijakan RLS (baca publik, tulis admin)
--   7. Bucket storage "dokumentasi" + kebijakan storage
--   8. Indeks bantu query

-- 1. Tabel kegiatan ----------------------------------------------------
create table if not exists public.kegiatan_internal_kantor (
  id uuid primary key default gen_random_uuid(),
  judul text not null,
  sub_judul text,
  jenis_kegiatan text,
  cerita_kegiatan text,
  tanggal_kegiatan timestamptz,
  image_path text,
  image_url text,
  published boolean not null default true,
  created_by uuid,
  created_at timestamptz not null default now()
);

-- Kolom tambahan untuk website publik (aman bila sudah ada).
alter table public.kegiatan_internal_kantor add column if not exists sub_judul text;
alter table public.kegiatan_internal_kantor add column if not exists jenis_kegiatan text;
alter table public.kegiatan_internal_kantor add column if not exists cerita_kegiatan text;
alter table public.kegiatan_internal_kantor add column if not exists tanggal_kegiatan timestamptz;
alter table public.kegiatan_internal_kantor add column if not exists image_path text;
alter table public.kegiatan_internal_kantor add column if not exists image_url text;
alter table public.kegiatan_internal_kantor add column if not exists published boolean not null default true;
alter table public.kegiatan_internal_kantor add column if not exists created_by uuid;
alter table public.kegiatan_internal_kantor add column if not exists created_at timestamptz not null default now();

-- Daftar foto tambahan (selain image_path) dalam satu kegiatan.
-- Bentuk: [{"path": "uuid.png", "url": "https://.../uuid.png"}, ...]
alter table public.kegiatan_internal_kantor add column if not exists photos jsonb not null default '[]'::jsonb;

-- 2. Tabel relasi foto (opsional) --------------------------------------
-- Dipakai bila portal admin menyimpan foto per kegiatan di tabel terpisah.
create table if not exists public.kegiatan_internal_photos (
  id bigint generated by default as identity primary key,
  kegiatan_id uuid references public.kegiatan_internal_kantor (id) on delete cascade,
  storage_path text not null,
  storage_url text,
  urutan integer not null default 0,
  created_at timestamptz not null default now()
);

create index if not exists kegiatan_internal_photos_kegiatan_idx
  on public.kegiatan_internal_photos (kegiatan_id, urutan);

-- 3. Taksonomi unit kerja ----------------------------------------------
-- Website mengelompokkan kegiatan berdasarkan kolom jenis_kegiatan.
-- Nilai di bawah adalah daftar yang dipakai portal admin; nilai lain tetap
-- diterima dan otomatis dinormalisasi menjadi slug oleh website.
create or replace function public.normalisasi_jenis_kegiatan(nilai text)
returns text
language sql
immutable
as $$
  select case
    when nilai is null or btrim(nilai) = '' then 'Lain-lain'
    when lower(btrim(nilai)) in ('pisah sambut', 'pisah-sambut', 'pisahsambut') then 'Pisah Sambut'
    when lower(btrim(nilai)) in ('rapat', 'rapat koordinasi', 'rapat kerja') then 'Rapat'
    when lower(btrim(nilai)) in ('pelatihan', 'training', 'workshop') then 'Pelatihan'
    when lower(btrim(nilai)) in ('sosialisasi', 'penyuluhan') then 'Sosialisasi'
    when lower(btrim(nilai)) in ('perayaan', 'hari besar', 'peringatan hari besar') then 'Perayaan'
    when lower(btrim(nilai)) in ('kunjungan', 'studi banding', 'kunjungan kerja') then 'Kunjungan'
    when lower(btrim(nilai)) in ('bakti sosial', 'baksos', 'kegiatan sosial') then 'Bakti Sosial'
    when lower(btrim(nilai)) in ('olahraga', 'sport', 'kegiatan olahraga') then 'Olahraga'
    when lower(btrim(nilai)) in ('lain-lain', 'lainnya', 'lain lain') then 'Lain-lain'
    else btrim(nilai)
  end;
$$;

-- Rapikan nilai lama supaya pengelompokan konsisten.
update public.kegiatan_internal_kantor
set jenis_kegiatan = public.normalisasi_jenis_kegiatan(jenis_kegiatan)
where jenis_kegiatan is distinct from public.normalisasi_jenis_kegiatan(jenis_kegiatan);

-- 4. View publik -------------------------------------------------------
-- Website membaca view ini lebih dulu (kolom seragam + jumlah foto),
-- lalu jatuh ke tabel dasar bila view belum ada.
create or replace view public.v_kegiatan_internal
with (security_invoker = true) as
select
  k.id,
  k.judul,
  k.sub_judul,
  public.normalisasi_jenis_kegiatan(k.jenis_kegiatan) as jenis_kegiatan,
  k.cerita_kegiatan,
  k.tanggal_kegiatan,
  k.image_path,
  k.image_url,
  k.photos,
  k.published,
  k.created_at,
  coalesce(
    (select count(*) from public.kegiatan_internal_photos p where p.kegiatan_id = k.id),
    0
  ) as jumlah_foto_relasi
from public.kegiatan_internal_kantor k;

-- 5. Function set_multi_foto -------------------------------------------
-- Simpan daftar foto satu kegiatan sekaligus (dipakai portal admin / dashboard).
-- p_photos: array of {"path": "...", "url": "..."} atau array string path.
create or replace function public.set_multi_foto(p_kegiatan_id uuid, p_photos jsonb)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.kegiatan_internal_kantor
  set photos = coalesce(p_photos, '[]'::jsonb)
  where id = p_kegiatan_id;
end;
$$;

revoke all on function public.set_multi_foto(uuid, jsonb) from public, anon;
grant execute on function public.set_multi_foto(uuid, jsonb) to authenticated, service_role;

-- 6. Hak akses + RLS ---------------------------------------------------
grant usage on schema public to anon, authenticated, service_role;

grant select on public.kegiatan_internal_kantor to anon, authenticated, service_role;
grant insert, update, delete on public.kegiatan_internal_kantor to authenticated, service_role;

grant select on public.kegiatan_internal_photos to anon, authenticated, service_role;
grant insert, update, delete on public.kegiatan_internal_photos to authenticated, service_role;
grant usage, select on sequence public.kegiatan_internal_photos_id_seq to authenticated, service_role;

grant select on public.v_kegiatan_internal to anon, authenticated, service_role;

alter table public.kegiatan_internal_kantor enable row level security;
alter table public.kegiatan_internal_photos enable row level security;

drop policy if exists "Public can read kegiatan internal" on public.kegiatan_internal_kantor;
create policy "Public can read kegiatan internal"
  on public.kegiatan_internal_kantor for select to anon, authenticated
  using (published = true);

drop policy if exists "Admins can read all kegiatan internal" on public.kegiatan_internal_kantor;
create policy "Admins can read all kegiatan internal"
  on public.kegiatan_internal_kantor for select to authenticated
  using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

drop policy if exists "Admins can insert kegiatan internal" on public.kegiatan_internal_kantor;
create policy "Admins can insert kegiatan internal"
  on public.kegiatan_internal_kantor for insert to authenticated
  with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

drop policy if exists "Admins can update kegiatan internal" on public.kegiatan_internal_kantor;
create policy "Admins can update kegiatan internal"
  on public.kegiatan_internal_kantor for update to authenticated
  using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin')
  with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

drop policy if exists "Admins can delete kegiatan internal" on public.kegiatan_internal_kantor;
create policy "Admins can delete kegiatan internal"
  on public.kegiatan_internal_kantor for delete to authenticated
  using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

drop policy if exists "Public can read kegiatan internal photos" on public.kegiatan_internal_photos;
create policy "Public can read kegiatan internal photos"
  on public.kegiatan_internal_photos for select to anon, authenticated
  using (true);

drop policy if exists "Admins can write kegiatan internal photos" on public.kegiatan_internal_photos;
create policy "Admins can write kegiatan internal photos"
  on public.kegiatan_internal_photos for all to authenticated
  using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin')
  with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

-- 7. Bucket penyimpanan foto ------------------------------------------
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('dokumentasi', 'dokumentasi', true, 8388608, array['image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do update
set name = excluded.name,
    public = excluded.public,
    file_size_limit = excluded.file_size_limit,
    allowed_mime_types = excluded.allowed_mime_types;

grant select on storage.objects to anon, authenticated;
grant insert, update, delete on storage.objects to authenticated, service_role;

drop policy if exists "Public can read dokumentasi photos" on storage.objects;
create policy "Public can read dokumentasi photos"
  on storage.objects for select to anon, authenticated
  using (bucket_id = 'dokumentasi');

drop policy if exists "Admins can upload dokumentasi photos" on storage.objects;
create policy "Admins can upload dokumentasi photos"
  on storage.objects for insert to authenticated
  with check (
    bucket_id = 'dokumentasi'
    and (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin'
  );

drop policy if exists "Admins can update dokumentasi photos" on storage.objects;
create policy "Admins can update dokumentasi photos"
  on storage.objects for update to authenticated
  using (
    bucket_id = 'dokumentasi'
    and (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin'
  )
  with check (
    bucket_id = 'dokumentasi'
    and (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin'
  );

drop policy if exists "Admins can delete dokumentasi photos" on storage.objects;
create policy "Admins can delete dokumentasi photos"
  on storage.objects for delete to authenticated
  using (
    bucket_id = 'dokumentasi'
    and (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin'
  );

-- 8. Indeks bantu query daftar kegiatan -------------------------------
create index if not exists kegiatan_internal_tanggal_idx
  on public.kegiatan_internal_kantor (tanggal_kegiatan desc nulls last, created_at desc);

create index if not exists kegiatan_internal_jenis_idx
  on public.kegiatan_internal_kantor (jenis_kegiatan);

create index if not exists kegiatan_internal_published_idx
  on public.kegiatan_internal_kantor (published, created_at desc);
