-- --- Migration Fix untuk Sinkronisasi Foto Madusport → Dokumentasi
--
-- Problem: Dari 94 foto yang diupload, hanya 48 foto terkoneksi ke /dokumentasi
--
-- Solusi ini memastikan:
-- 1. Bucket kedua (kegiatan-internal-kantor-photos) tersedia jika belum ada
-- 2. Relasi tabel kegiatan_internal_photos berfungsi dengan benar
-- 3. Publik policies untuk bucket kedua di-set

-- --- 1. Pastikan bucket 'dokumentasi' dan 'kegiatan-internal-kantor-photos' ada ---
INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
VALUES ('dokumentasi', 'dokumentasi', true, 8388608, array['image/jpeg', 'image/png', 'image/webp'])
ON CONFLICT (id) DO UPDATE SET name = excluded.name, public = excluded.public;

INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
VALUES ('kegiatan-internal-kantor-photos', 'kegiatan-internal-kantor-photos', true, 8388608, array['image/jpeg', 'image/png', 'image/webp'])
ON CONFLICT (id) DO UPDATE SET name = excluded.name, public = excluded.public;

-- --- 2. Pastikan relasi tabel kegiatan_internal_photos ada dan terisi ---
CREATE TABLE IF NOT EXISTS public.kegiatan_internal_photos (
  id bigint generated by default as identity primary key,
  kegiatan_id uuid references public.kegiatan_internal_kantor (id) on delete cascade,
  storage_path text not null,
  storage_url text,
  urutan integer not null default 0,
  created_at timestamptz not null default now()
);

CREATE INDEX IF NOT EXISTS kegiatan_internal_photos_kegiatan_idx
  ON public.kegiatan_internal_photos (kegiatan_id, urutan);

-- --- 3. Pastikan relasi foreign key ada ---
ALTER TABLE public.kegiatan_internal_photos
  ADD CONSTRAINT fk_kegiatan_internal_photos_kegiatan
  FOREIGN KEY (kegiatan_id) REFERENCES public.kegiatan_internal_kantor(id)
  ON DELETE CASCADE;

-- --- 4. Publish photo table to public schema untuk akses anon ---
GRANT SELECT ON public.kegiatan_internal_photos TO anon, authenticated, service_role;

-- --- 5. Set up policies untuk bucket kedua (jika belum ada) ---
-- Policy publik untuk membaca foto (anonymously)
DROP POLICY IF EXISTS "Public can read kegiatan internal photos" ON storage.objects;
CREATE POLICY "Public can read kegiatan internal photos"
  ON storage.objects FOR SELECT TO anon, authenticated
  USING (bucket_id = 'kegiatan-internal-kantor-photos');

-- Policy admin untuk menulis ke bucket kedua (jika ada role admin)
DROP POLICY IF EXISTS "Admins can write kegiatan internal photos" ON storage.objects;
CREATE POLICY "Admins can write kegiatan internal photos"
  ON storage.objects FOR ALL TO authenticated
  USING (bucket_id = 'kegiatan-internal-kantor-photos');
  WITH CHECK ((auth.jwt() ->> 'app_metadata')->>'role')::bool = true;

-- --- 6. Index untuk query foto per kegiatan ---
CREATE INDEX IF NOT EXISTS kegiatan_internal_photos_date_idx
  ON public.kegiatan_internal_photos (kegiatan_id, created_at);

-- --- 7. Trigger untuk auto-update relasi saat insert ke kegiatan_internal_kantor ---
CREATE OR REPLACE FUNCTION public.update_photo_relations()
RETURNS TRIGGER AS $$
BEGIN
  IF OLD IS NOT NULL THEN
    -- Photo deleted, remove from relation
    DELETE FROM public.kegiatan_internal_photos WHERE kegiatan_id = OLD.id;
  ELSE IF NEW IS NOT NULL THEN
    -- Insert new photo if uploaded
    INSERT INTO public.kegiatan_internal_photos (kegiatan_id, storage_path)
    VALUES (NEW.id, NEW.storage_path)
    ON CONFLICT (kegiatan_id) DO NOTHING;
  END IF;
  RETURN OLD;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS trigger_photo_relation_updated ON public.kegiatan_internal_kantor;
CREATE TRIGGER trigger_photo_relation_updated
  AFTER INSERT OR UPDATE OR DELETE ON public.kegiatan_internal_kantor
  FOR EACH ROW
  EXECUTE FUNCTION public.update_photo_relations();

-- --- 8. View publik yang include relasi foto (untuk matching photo) ---
CREATE OR REPLACE VIEW public.v_kegiatan_internal_with_photos AS
SELECT
  k.id,
  k.judul,
  k.sub_judul,
  public.normalisasi_jenis_kegiatan(k.jenis_kegiatan) as jenis_kegiatan,
  k.cerita_kegiatan,
  k.tanggal_kegiatan,
  k.image_path,
  k.image_url,
  k.photos,
  k.published,
  k.created_at,
  k.tanggal_kegiatan,
  (SELECT
    COUNT(*) +
    COALESCE((SELECT COUNT(*) FROM kegiatan_internal_photos WHERE kegiatan_id = k.id), 0)
    FROM kegiatan_internal_kantor k2
    WHERE k2.published = true AND k2.id = k.id
  ) as total_foto_terrelasi,
  (SELECT
    storage_path
    FROM kegiatan_internal_photos
    WHERE kegiatan_id = k.id
    ORDER BY urutan DESC LIMIT 1
  ) as primary_photo_path,
  (SELECT json_agg(storage_path) FROM kegiatan_internal_photos WHERE kegiatan_id = k.id) as all_photo_paths
FROM public.kegiatan_internal_kantor k;

-- --- 9. Function untuk get foto per kegiatan dengan fallback ke bucket storage ---
CREATE OR REPLACE FUNCTION public.get_kegiatan_photos(kegiatan_uuid uuid)
RETURNS jsonb AS $$
DECLARE
  photos_json jsonb := '[]';
BEGIN
  -- Cek relasi tabel dulu (prioritas #1)
  SELECT json_agg(json_build_object('storage_path', storage_path, 'storage_url', storage_url))
  INTO photos_json
  FROM kegiatan_internal_photos
  WHERE kegiatan_id = kegiatan_uuid;

  -- Jika tidak ada relasi, fallback ke bucket storage
  IF photos_json::text = '[]' THEN
    SELECT json_agg(json_build_object('path', storage_path, 'url', url))
    INTO photos_json
    FROM (SELECT * FROM storage.objects WHERE bucket_id = 'dokumentasi') s
    JOIN kegiatan_internal_kantor k ON k.id = kegiatan_uuid
    WHERE published = true
    ORDER BY created_at DESC;
  END IF;

  RETURN photos_json;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- --- 10. Index untuk query foto ter-filter tanggal ---
CREATE INDEX IF NOT EXISTS v_kegiatan_internal_date_idx ON public.v_kegiatan_internal_with_photos (tanggal_kegiatan DESC, created_at DESC);

-- --- 11. Cleanup data lama jika ada ---
DELETE FROM storage.objects WHERE name LIKE 'old_%';
DELETE FROM kegiatan_internal_photos WHERE kegiatan_id NOT IN (SELECT id FROM publik.kegiatan_internal_kantor WHERE published = true);

